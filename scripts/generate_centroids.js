// Generates topic_centroids.js — pre-computed 384-float centroid vectors for each topic.
// Uses the same all-MiniLM-L6-v2 model as the extension so vectors are compatible.
// Usage: node scripts/generate_centroids.js

const { pipeline, env } = require('@xenova/transformers');
const fs = require('fs');
const path = require('path');

env.localModelPath = path.join(__dirname, '..', 'models') + path.sep;
env.allowLocalModels = true;
env.allowRemoteModels = false;
env.useBrowserCache = false;

// Single descriptive sentence per topic — broad enough to cover edge cases.
// Deliberately includes overlapping concepts (e.g. "internet culture" in both
// tech and commentary) so ambiguous titles land in the closest bucket.
const TOPICS = {
  gaming:      'video games gameplay walkthrough esports competitive gaming strategy game console PC gaming',
  tech:        'software engineering programming coding tutorial hardware review computers technology AI internet',
  finance:     'stock market investing personal finance cryptocurrency wealth management economics trading',
  science:     'scientific research physics chemistry biology space exploration experiments discoveries',
  history:     'historical events world wars empires military history political revolutions battles dynasties colonial history cold war documentary history assassination coup uprising resistance occupation',
  comedy:      'funny videos comedy sketches humor jokes pranks stand-up comedy satire memes fails',
  music:       'music songs albums live concert artist musicians bands instruments production',
  sports:      'sports highlights football basketball soccer athletics tournament fitness training',
  food:        'cooking recipes restaurant food review chef kitchen cuisine baking meals',
  film_tv:     'movies TV shows film reviews Netflix streaming anime cinema actors directors',
  commentary:  'internet commentary creator drama exposed cancelled influencer controversy hot take unpopular opinion podcast video essay reacting responding YouTube creator culture deep dive',
  general:     'general interest vlog lifestyle entertainment daily life personal stories',
};

async function main() {
  console.log('Loading all-MiniLM-L6-v2...');
  const embedder = await pipeline('feature-extraction', 'Xenova/all-MiniLM-L6-v2', { quantized: true });

  const centroids = {};
  for (const [topic, desc] of Object.entries(TOPICS)) {
    const out = await embedder(desc, { pooling: 'mean', normalize: true });
    centroids[topic] = Array.from(out.data);
    console.log(`  embedded: ${topic}`);
  }

  const entries = Object.entries(centroids)
    .map(([k, v]) => `  ${k}: [${v.join(',')}]`)
    .join(',\n');

  const output = `// Auto-generated by scripts/generate_centroids.js — do not edit manually.
// Re-run that script if you change the descriptive strings.
// Compatible with all-MiniLM-L6-v2 (quantized, mean-pooled, L2-normalized).
const YTAP_TOPIC_CENTROIDS = {
${entries}
};
`;

  const outPath = path.join(__dirname, '..', 'topic_centroids.js');
  fs.writeFileSync(outPath, output, 'utf8');
  console.log(`\nWrote ${outPath}`);
}

main().catch(err => { console.error(err); process.exit(1); });
